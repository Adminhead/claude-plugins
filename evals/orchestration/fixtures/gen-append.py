#!/usr/bin/env python3
"""Writes evals/append-*/case.yaml: the orchestration prompt body (agents/orchestration.md without
its frontmatter, as claude-orchestrate appends it) as execution.append_system_prompt.

claude plugin eval takes append_system_prompt as text, not a file path, so the body is copied into
each append-* case. Run after editing plugins/orchestration/agents/orchestration.md:

    python3 -I evals/orchestration/fixtures/gen-append.py          # rewrite
    python3 -I evals/orchestration/fixtures/gen-append.py --check  # exit 1 when a case is stale
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
AGENT = ROOT / "plugins/orchestration/agents/orchestration.md"


def body(text: str) -> str:
    """Same as the launcher's awk: drop everything up to the second '---' line, then leading blanks."""
    lines = text.splitlines()
    seen = 0
    out = []
    for line in lines:
        if seen >= 2:
            out.append(line)
        if line == "---":
            seen += 1
    while out and not out[0].strip():
        out.pop(0)
    return "\n".join(out) + "\n"


def case_yaml(name: str, text: str) -> str:
    indented = "".join(("    " + l if l.strip() else "") + "\n" for l in text.splitlines())
    return (
        "# Generated by fixtures/gen-append.py from plugins/orchestration/agents/orchestration.md. Do not edit.\n"
        'schema_version: "1.1"\n'
        f"name: {json.dumps(name)}\n"
        "execution:\n"
        "  append_system_prompt: |\n"
        f"{indented}"
    )


def main() -> int:
    check = "--check" in sys.argv[1:]
    text = body(AGENT.read_text())
    stale = 0
    for case in sorted((HERE.parent / "evals").glob("append-*")):
        want = case_yaml(case.name, text)
        path = case / "case.yaml"
        if check:
            if not path.exists() or path.read_text() != want:
                print(f"stale: {path.relative_to(ROOT)}")
                stale += 1
        else:
            path.write_text(want)
            print(f"wrote {path.relative_to(ROOT)}")
    return 1 if stale else 0


sys.exit(main())
